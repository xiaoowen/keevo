//! 短认证串的显示（`spec/ipc.md` §4.2）：SAS 词表 v1。
//!
//! 6 个 SAS 字节各对应一个词，两端都同时显示中文词与英文词（同一个字节的两个词互为翻译）。
//! 词表只是显示映射，不改变握手；两端的词表版本不一致时用户看到的词不同，会按不一致拒绝，是安全的方向。

/// 一个字节对应的词。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SasWord {
    /// 中文词（两个汉字）。
    pub zh: &'static str,
    /// 英文词（3–9 个小写字母）。
    pub en: &'static str,
}

/// 词表版本，与 `spec/sas-wordlist-v1.tsv` 对应。
pub const WORDLIST_VERSION: u32 = 1;

/// 6 个 SAS 字节对应的词，按字节顺序。
#[must_use]
pub fn sas_words(sas: &[u8; 6]) -> [SasWord; 6] {
    sas.map(word)
}

/// 一个字节对应的词。
#[must_use]
pub fn word(byte: u8) -> SasWord {
    let (zh, en) = V1.get(usize::from(byte)).copied().unwrap_or(("?", "?"));
    SasWord { zh, en }
}

